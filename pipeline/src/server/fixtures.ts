const dayOrBlank = (today: string, offset: number | undefined) =>
  offset === undefined ? "" : addDays(today, offset)

const hash = (value: string) => {
  let total = 0
  for (const char of value) total = (total * 33 + char.charCodeAt(0)) >>> 0
  return total
}

